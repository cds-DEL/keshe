static HAL_StatusTypeDef ssd1306_WriteCommand(uint8_t command)
{
  uint8_t data[2] = {0x00, command};
  return HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR, data, 2, 10);
}

void ssd1306_Init(void)
{
  HAL_Delay(100);

  ssd1306_WriteCommand(0xAE); // Display off
  ssd1306_WriteCommand(0x20); // Set Memory Addressing Mode
  ssd1306_WriteCommand(0x00); // Horizontal addressing mode
  ssd1306_WriteCommand(0xB0); // Set Page Start Address for Page Addressing Mode
  ssd1306_WriteCommand(0xC8); // COM Output Scan Direction
  ssd1306_WriteCommand(0x00); // Set low column address
  ssd1306_WriteCommand(0x10); // Set high column address
  ssd1306_WriteCommand(0x40); // Set start line address
  ssd1306_WriteCommand(0x81); // Set contrast control
  ssd1306_WriteCommand(0x7F);
  ssd1306_WriteCommand(0xA1); // Set segment re-map (use A1 for this module orientation)
  ssd1306_WriteCommand(0xA6); // Set normal display
  ssd1306_WriteCommand(0xA8); // Set multiplex ratio
  ssd1306_WriteCommand(0x3F);
  ssd1306_WriteCommand(0xA4); // Output follows RAM content
  ssd1306_WriteCommand(0xD3); // Set display offset
  ssd1306_WriteCommand(0x00);
  ssd1306_WriteCommand(0xD5); // Set display clock divide ratio/oscillator frequency
  ssd1306_WriteCommand(0xF0);
  ssd1306_WriteCommand(0xD9); // Set pre-charge period
  ssd1306_WriteCommand(0x22);
  ssd1306_WriteCommand(0xDA); // Set COM pins hardware configuration
  ssd1306_WriteCommand(0x12);
  ssd1306_WriteCommand(0xDB); // Set vcomh deselect level
  ssd1306_WriteCommand(0x20);
  ssd1306_WriteCommand(0x8D); // Charge pump setting
  ssd1306_WriteCommand(0x14);
  ssd1306_WriteCommand(0xAF); // Display on

  ssd1306_Clear();
  ssd1306_UpdateScreen();
}

void ssd1306_UpdateScreen(void)
{
  for (uint8_t page = 0; page < 8; page++)
  {
    ssd1306_WriteCommand(0xB0 + page);
    ssd1306_WriteCommand(0x00);
    ssd1306_WriteCommand(0x10);

    uint8_t data[SSD1306_WIDTH + 1];
    data[0] = 0x40;
    memcpy(&data[1], &SSD1306_Buffer[SSD1306_WIDTH * page], SSD1306_WIDTH);
    HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR, data, SSD1306_WIDTH + 1, 100);
  }
}

void ssd1306_Fill(uint8_t color)
{
  memset(SSD1306_Buffer, color ? 0xFF : 0x00, sizeof(SSD1306_Buffer));
}

void ssd1306_Clear(void)
{
  ssd1306_Fill(SSD1306_COLOR_BLACK);
  ssd1306_GotoXY(0, 0);
}

void ssd1306_GotoXY(uint8_t x, uint8_t y)
{
  SSD1306_CurrentX = x;
  SSD1306_CurrentY = y;
}

void ssd1306_PutChar(char ch)
{
  if (ch < 32 || ch > 127)
  {
    ch = '?';
  }

  if (SSD1306_CurrentX + 6 > SSD1306_WIDTH)
  {
    SSD1306_CurrentX = 0;
    SSD1306_CurrentY += 8;
  }

  uint8_t page = SSD1306_CurrentY / 8;
  uint8_t shift = SSD1306_CurrentY % 8;
  uint16_t index = (ch - 32) * 5;

  for (uint8_t i = 0; i < 5; i++)
  {
    uint8_t line = Font5x8[index + i];
    if (page < 8)
    {
      SSD1306_Buffer[SSD1306_CurrentX + page * SSD1306_WIDTH + i] &= ~(0xFF << shift);
      SSD1306_Buffer[SSD1306_CurrentX + page * SSD1306_WIDTH + i] |= line << shift;
    }
    if (shift && (page + 1) < 8)
    {
      SSD1306_Buffer[SSD1306_CurrentX + (page + 1) * SSD1306_WIDTH + i] &= ~(0xFF >> (8 - shift));
      SSD1306_Buffer[SSD1306_CurrentX + (page + 1) * SSD1306_WIDTH + i] |= line >> (8 - shift);
    }
  }

  SSD1306_CurrentX += 6;
}

void ssd1306_PutBigChar(char ch)
{
  uint8_t digitIndex;

  if (ch >= '0' && ch <= '9')
  {
    digitIndex = ch - '0';
  }
  else if (ch == ':')
  {
    digitIndex = 10;
  }
  else
  {
    return;
  }

  if (SSD1306_CurrentX + 8 > SSD1306_WIDTH)
  {
    SSD1306_CurrentX = 0;
    SSD1306_CurrentY += 16;
  }

  for (uint8_t col = 0; col < 8; col++)
  {
    uint8_t column_low = Font8x16Digits[digitIndex][col];
    uint8_t column_high = Font8x16Digits[digitIndex][col + 8];
    uint16_t bufferIndex = SSD1306_CurrentX + (SSD1306_CurrentY / 8) * SSD1306_WIDTH + col;

    if ((SSD1306_CurrentY / 8) < 8)
    {
      SSD1306_Buffer[bufferIndex] = column_low;
    }
    if ((SSD1306_CurrentY / 8 + 1) < 8)
    {
      SSD1306_Buffer[bufferIndex + SSD1306_WIDTH] = column_high;
    }
  }

  SSD1306_CurrentX += 8;
}

static void ssd1306_DrawPixel(uint8_t x, uint8_t y, SSD1306_COLOR_t color)
{
  if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT)
  {
    return;
  }

  if (color == SSD1306_COLOR_WHITE)
  {
    SSD1306_Buffer[x + (y / 8) * SSD1306_WIDTH] |= 1 << (y % 8);
  }
  else
  {
    SSD1306_Buffer[x + (y / 8) * SSD1306_WIDTH] &= ~(1 << (y % 8));
  }
}

void ssd1306_PutBigString2x(const char* str, uint8_t x, uint8_t y)
{
  uint8_t posX = x;

  while (*str)
  {
    char ch = *str++;
    uint8_t index;
    if (ch >= '0' && ch <= '9')
    {
      index = ch - '0';
    }
    else if (ch == ':')
    {
      index = 10;
    }
    else
    {
      posX += 16;
      continue;
    }

    for (uint8_t row = 0; row < 16; row++)
    {
      uint8_t line = Font8x16Digits[index][row];
      for (uint8_t col = 0; col < 8; col++)
      {
        if (line & (1 << (7 - col)))
        {
          uint8_t baseX = posX + (col << 1);
          uint8_t baseY = y + (row << 1);
          ssd1306_DrawPixel(baseX, baseY, SSD1306_COLOR_WHITE);
          ssd1306_DrawPixel(baseX + 1, baseY, SSD1306_COLOR_WHITE);
          ssd1306_DrawPixel(baseX, baseY + 1, SSD1306_COLOR_WHITE);
          ssd1306_DrawPixel(baseX + 1, baseY + 1, SSD1306_COLOR_WHITE);
        }
      }
    }

    posX += 16;
  }
}

void ssd1306_PutBigString4x(const char* str, uint8_t x, uint8_t y)
{
  const uint8_t scale = 4;
  uint8_t posX = x;

  while (*str)
  {
    char ch = *str++;
    uint8_t index;
    if (ch >= '0' && ch <= '9')
    {
      index = ch - '0';
    }
    else if (ch == ':')
    {
      index = 10;
    }
    else
    {
      posX += (8 * scale);
      continue;
    }

    for (uint8_t row = 0; row < 16; row++)
    {
      uint8_t line = Font8x16Digits[index][row];
      for (uint8_t col = 0; col < 8; col++)
      {
        if (line & (1 << (7 - col)))
        {
          uint8_t baseX = posX + col * scale;
          uint8_t baseY = y + row * scale;
          for (uint8_t dy = 0; dy < scale; dy++)
          {
            for (uint8_t dx = 0; dx < scale; dx++)
            {
              ssd1306_DrawPixel(baseX + dx, baseY + dy, SSD1306_COLOR_WHITE);
            }
          }
        }
      }
    }

    posX += (8 * scale);
  }
}

void ssd1306_PutBigStringScaled(const char* str, uint8_t x, uint8_t y, uint8_t scale, uint8_t spacing)
{
  if (scale < 1) scale = 1;
  uint8_t posX = x;
  size_t len = strlen(str);

  for (size_t s = 0; s < len; s++)
  {
    char ch = str[s];
    uint8_t index;
    if (ch >= '0' && ch <= '9') index = ch - '0';
    else if (ch == ':') index = 10;
    else { posX += 8 * scale + spacing; continue; }

    for (uint8_t row = 0; row < 16; row++)
    {
      uint8_t line = Font8x16Digits[index][row];
      for (uint8_t col = 0; col < 8; col++)
      {
        if (line & (1 << (7 - col)))
        {
          uint8_t baseX = posX + col * scale;
          uint8_t baseY = y + row * scale;
          for (uint8_t dy = 0; dy < scale; dy++)
          {
            for (uint8_t dx = 0; dx < scale; dx++)
            {
              ssd1306_DrawPixel(baseX + dx, baseY + dy, SSD1306_COLOR_WHITE);
            }
          }
        }
      }
    }

    posX += 8 * scale + spacing;
  }
}

void ssd1306_PutString(const char* str)
{
  while (*str)
  {
    ssd1306_PutChar(*str++);
  }
}
